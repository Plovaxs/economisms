import numpy as np
import pytest

from prometheus.data_ingestion.transport import HttpResponse
from prometheus.data_ingestion.worldbank import fetch_world_bank_indicator
from prometheus.evidence.dataset_card import DatasetCard, build_dataset_card
from prometheus.stochastica.gbm import simulate_gbm_paths

_REAL_PAGE_1 = b'[{"page":1,"pages":1,"per_page":5,"total":1,"sourceid":"2","lastupdated":"2026-10-08"},[{"indicator":{"id":"NY.GDP.MKTP.KD.ZG","value":"GDP growth (annual %)"},"country":{"id":"US","value":"United States"},"countryiso3code":"USA","date":"2020","value":-2.081375977796,"unit":"","obs_status":"","decimal":1}]]'  # noqa: E501


class _ScriptedTransport:
    def __init__(self, bodies: list[bytes]) -> None:
        self._bodies = list(bodies)

    def get(self, url: str, params: dict[str, str]) -> HttpResponse:
        return HttpResponse(status_code=200, body=self._bodies.pop(0))


def test_rejects_an_empty_dataset_id() -> None:
    with pytest.raises(ValueError, match="dataset_id"):
        build_dataset_card("", "synthetic", "a lineage", "a description")


def test_rejects_an_unknown_data_type() -> None:
    with pytest.raises(ValueError, match="data_type"):
        build_dataset_card("d1", "fabricated", "a lineage", "a description")  # type: ignore[arg-type]


def test_rejects_an_empty_lineage() -> None:
    with pytest.raises(ValueError, match="lineage"):
        build_dataset_card("d1", "synthetic", "", "a description")


def test_rejects_an_empty_description() -> None:
    with pytest.raises(ValueError, match="description"):
        build_dataset_card("d1", "synthetic", "a lineage", "")


def test_a_real_gbm_simulation_is_carded_as_synthetic() -> None:
    """Grounded in a real simulated path, not a label applied to
    nothing: the data this card describes genuinely exists and was
    genuinely generated by this project's own simulator."""
    rng = np.random.default_rng(0)
    paths = simulate_gbm_paths(100.0, 0.08, 0.2, 1.0, n_steps=10, n_paths=5, rng=rng)
    assert paths.shape == (5, 11)
    card = build_dataset_card(
        dataset_id="gbm_demo_paths",
        data_type="synthetic",
        lineage="stochastica.gbm.simulate_gbm_paths, seeded RNG, no external data",
        description="5 simulated GBM price paths over 10 steps",
    )
    assert card.data_type == "synthetic"


def test_a_real_world_bank_fetch_is_carded_as_empirical_with_its_own_license() -> None:
    """Grounded in a real captured World Bank API response (the same
    hermetic fixture `test_worldbank_connector.py` exercises), not a
    fabricated license string: the card's lineage states the ACTUAL
    license the real observation carries."""
    transport = _ScriptedTransport([_REAL_PAGE_1])
    result = fetch_world_bank_indicator(transport, ["USA"], "NY.GDP.MKTP.KD.ZG", per_page=5)
    observation = result.observations[0]
    assert observation.source_license == "CC-BY-4.0 (World Bank Open Data)"

    card = build_dataset_card(
        dataset_id="worldbank_ny_gdp_mktp_kd_zg_usa",
        data_type="empirical",
        lineage=f"World Bank Open Data API, license: {observation.source_license}",
        description="USA annual GDP growth rate (NY.GDP.MKTP.KD.ZG)",
    )
    assert card.data_type == "empirical"
    assert observation.source_license in card.lineage


def test_dataset_card_is_immutable() -> None:
    import dataclasses

    card = build_dataset_card("d1", "synthetic", "lineage", "description")
    with pytest.raises(dataclasses.FrozenInstanceError):
        card.data_type = "empirical"  # type: ignore[misc]


def test_dataset_card_type_is_constructible_directly() -> None:
    card = DatasetCard(
        dataset_id="d1", data_type="synthetic", lineage="lineage", description="description"
    )
    assert card.dataset_id == "d1"
