"""Dataset cards: synthetic-vs-empirical labels and data lineage
(DAT-14: "document synthetic-vs-empirical labels and dataset cards";
acceptance criterion: "every published result identifies data lineage
and type").

`DataType` is deliberately a closed, two-value vocabulary -- a dataset
in this repository is either `"synthetic"` (generated by one of this
project's own stochastic simulators, e.g. `stochastica.gbm`) or
`"empirical"` (real, externally sourced data, e.g. `data_ingestion.
worldbank`); there is no third, ambiguous category a caller could use
to avoid declaring which one applies. `DatasetCard.lineage` is a short,
human-readable statement of exactly where the data came from -- not a
generic "see source code" placeholder -- and `build_dataset_card` has
no default for `data_type` or `lineage`, so a caller can never end up
with a published result whose card is silently missing either.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Literal

DataType = Literal["synthetic", "empirical"]

_DATA_TYPES: frozenset[str] = frozenset({"synthetic", "empirical"})


@dataclass(frozen=True, slots=True)
class DatasetCard:
    dataset_id: str
    data_type: DataType
    lineage: str
    description: str

    def __post_init__(self) -> None:
        if not self.dataset_id:
            raise ValueError("dataset_id must not be empty")
        if self.data_type not in _DATA_TYPES:
            raise ValueError(
                f"data_type must be one of {sorted(_DATA_TYPES)}, got {self.data_type!r}"
            )
        if not self.lineage:
            raise ValueError("lineage must not be empty")
        if not self.description:
            raise ValueError("description must not be empty")


def build_dataset_card(
    dataset_id: str, data_type: DataType, lineage: str, description: str
) -> DatasetCard:
    return DatasetCard(
        dataset_id=dataset_id, data_type=data_type, lineage=lineage, description=description
    )
